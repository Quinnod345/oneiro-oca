class FeatureDatasetV7:
    """Loads pre-pool features (NHWC) for all manifest samples that have them.

    Phase 8: synthesizes BT pairs from regression scores within the train
    split.  Falls back to flywheel comparisons.json when those exist (and
    deduplicates so synth pairs don't collide with real pairs).
    """

    def __init__(self, max_synth_pairs: int = DEFAULT_MAX_SYNTH_PAIRS,
                 pair_overall_margin: float = DEFAULT_PAIR_MARGIN,
                 pair_dim_margin: float = DEFAULT_PAIR_DIM_MARGIN):

        # ── Load pre-features sidecar ──
        if not PRE_FEATURES_PATH.exists():
            raise FileNotFoundError(
                f"No pre-pool features at {PRE_FEATURES_PATH}. "
                f"Run `python extract_features.py --include-pre` first."
            )
        with np.load(PRE_FEATURES_PATH) as npz:
            self.pre_indices = npz["indices"].astype(np.int64)
            self.pre_features = npz["features"].astype(np.float32)
        idx_to_pre = {int(i): k for k, i in enumerate(self.pre_indices.tolist())}

        # ── Load manifest and align ──
        with open(MANIFEST_PATH) as f:
            manifest = json.load(f)
        self.critique_by_cycle = load_critique_embeddings()

        self.pre_idx_in_dataset = []  # which row in self.pre_features
        self.targets = []
        self.code_features = []
        self.critique_embeddings = []
        self.critique_mask = []
        self.names = []
        self.manifest_indices = []   # original manifest index for joining pairs

        # Path → row in this dataset, used for flywheel pair joining
        self.path_to_idx = {}

        matched = 0
        for mi, sample in enumerate(manifest["samples"]):
            if mi not in idx_to_pre:
                continue
            scores = sample.get("scores", {})
            target = [float(scores.get(n, 0.5)) for n in SCORE_NAMES]

            row = len(self.pre_idx_in_dataset)
            self.pre_idx_in_dataset.append(idx_to_pre[mi])
            self.targets.append(target)
            self.manifest_indices.append(mi)

            code = sample.get("code_features")
            self.code_features.append(code if code and len(code) == 64 else [0.0] * 64)

            meta = sample.get("metadata", {})
            cycle_id = extract_cycle_id(meta.get("source_name", ""))
            if cycle_id is None:
                cycle_id = extract_cycle_id(meta.get("code_path", ""))
            if cycle_id is not None and cycle_id in self.critique_by_cycle:
                self.critique_embeddings.append(self.critique_by_cycle[cycle_id].tolist())
                self.critique_mask.append(1.0)
                matched += 1
            else:
                self.critique_embeddings.append([0.0] * CRITIQUE_DIM)
                self.critique_mask.append(0.0)

            self.names.append(meta.get("source_name") or meta.get("category", "unknown"))

            for k in ("image", "screenshot_path"):
                p = sample.get(k)
                if p:
                    self.path_to_idx[p] = row

        self.n_matched = matched
        self.n_samples = len(self.pre_idx_in_dataset)

        # ── Real flywheel pairs ──
        self.real_pairs = []
        if COMPARISONS_PATH.exists():
            comps = json.loads(COMPARISONS_PATH.read_text())
            for pair in comps.get("pairs", []):
                ia = self.path_to_idx.get(pair.get("image_a"))
                ib = self.path_to_idx.get(pair.get("image_b"))
                if ia is None or ib is None:
                    continue
                winner = np.zeros(OUTPUT_DIM, dtype=np.float32)
                margin = np.zeros(OUTPUT_DIM, dtype=np.float32)
                prefs = pair.get("preferences", {})
                for d, name in enumerate(SCORE_NAMES):
                    p = prefs.get(name, {})
                    w = p.get("winner")
                    winner[d] = 1.0 if w == "A" else -1.0 if w == "B" else 0.0
                    margin[d] = float(p.get("margin", 0.0))
                self.real_pairs.append((ia, ib, winner, margin))

        # Synthesized pairs are filled in after split() because we want to
        # restrict synthesis to the train split.
        self.synth_pairs = []
        self.pair_overall_margin = pair_overall_margin
        self.pair_dim_margin = pair_dim_margin
        self.max_synth_pairs = max_synth_pairs

    def __len__(self):
        return self.n_samples

    def split(self, val_ratio=0.15, seed=42):
        rng = np.random.default_rng(seed)
        n = self.n_samples
        indices = np.arange(n)
        rng.shuffle(indices)
        n_val = max(2, int(n * val_ratio))
        val_idx = set(indices[:n_val].tolist())
        train_idx = [i for i in range(n) if i not in val_idx]
        val_idx = list(val_idx)

        # Synthesize pairs over the train split only — leak-free
        self.synth_pairs = self._synthesize_pairs(train_idx, rng)
        return train_idx, val_idx

    def _synthesize_pairs(self, train_idx, rng):
        """Build BT pairs from train-split samples whose overall margins exceed
        threshold.  Per-dim winners are derived from per-dim margins."""
        targets = np.asarray(self.targets, dtype=np.float32)
        overall_idx = SCORE_NAMES.index("overall_aesthetic")

        candidates = []  # (i, j, overall_margin)
        train_set = list(train_idx)
        # Reservoir-style: enumerate pairs but cap the search.
        # 385 train samples → 73,920 unordered pairs.  Sample a random subset
        # of pairs to consider for tractability, then filter by margin.
        max_to_examine = min(50_000, len(train_set) * (len(train_set) - 1) // 2)
        examined = 0
        for i in range(len(train_set)):
            for j in range(i + 1, len(train_set)):
                if examined >= max_to_examine:
                    break
                examined += 1
                a, b = train_set[i], train_set[j]
                m = abs(targets[a, overall_idx] - targets[b, overall_idx])
                if m > self.pair_overall_margin:
                    candidates.append((a, b, m))

        if not candidates:
            return []

        # Sample uniformly to cap (preserves diversity better than top-k by margin)
        if len(candidates) > self.max_synth_pairs:
            picks = rng.choice(len(candidates), self.max_synth_pairs, replace=False)
            candidates = [candidates[k] for k in picks]

        pairs = []
        for a, b, _m in candidates:
            winner = np.zeros(OUTPUT_DIM, dtype=np.float32)
            margin = np.zeros(OUTPUT_DIM, dtype=np.float32)
            for d in range(OUTPUT_DIM):
                ma = float(targets[a, d])
                mb = float(targets[b, d])
                diff = ma - mb
                if abs(diff) > self.pair_dim_margin:
                    winner[d] = 1.0 if diff > 0 else -1.0
                    margin[d] = abs(diff)
            pairs.append((a, b, winner, margin))
        return pairs

    @property
    def all_pairs(self):
        return self.real_pairs + self.synth_pairs

    def get_regression_batch(self, indices):
        feats = mx.array(self.pre_features[[self.pre_idx_in_dataset[i] for i in indices]])
        targets = mx.array(np.array([self.targets[i] for i in indices], dtype=np.float32))
        codes = mx.array(np.array([self.code_features[i] for i in indices], dtype=np.float32))
        crits = mx.array(np.array([self.critique_embeddings[i] for i in indices], dtype=np.float32))
        mask = mx.array(np.array([self.critique_mask[i] for i in indices], dtype=np.float32))
        return feats, targets, codes, crits, mask

    def get_preference_batch(self, indices):
        if not indices:
            empty4 = mx.zeros((0, 7, 7, 320))
            return empty4, empty4, mx.zeros((0, 64)), mx.zeros((0, 64)), \
                   mx.zeros((0, OUTPUT_DIM)), mx.zeros((0, OUTPUT_DIM))

        pairs = self.all_pairs
        feat_a, feat_b, code_a, code_b, win, marg = [], [], [], [], [], []
        for k in indices:
            a, b, w, m = pairs[k]
            feat_a.append(self.pre_features[self.pre_idx_in_dataset[a]])
            feat_b.append(self.pre_features[self.pre_idx_in_dataset[b]])
            code_a.append(self.code_features[a])
            code_b.append(self.code_features[b])
            win.append(w)
            marg.append(m)

        return (mx.array(np.stack(feat_a, dtype=np.float32)),
                mx.array(np.stack(feat_b, dtype=np.float32)),
                mx.array(np.stack(code_a, dtype=np.float32).astype(np.float32)),
                mx.array(np.stack(code_b, dtype=np.float32).astype(np.float32)),
                mx.array(np.stack(win, dtype=np.float32).astype(np.float32)),
                mx.array(np.stack(marg, dtype=np.float32).astype(np.float32)))


