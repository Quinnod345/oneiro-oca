# DESIGN HEAD V7 — v6 architecture + trainable backbone tail
# ═══════════════════════════════════════════════════


class FeatureAdapter(nn.Module):
    def __init__(self, dim: int = 1280, rank: int = DEFAULT_ADAPTER_RANK,
                 init_alpha: float = DEFAULT_ADAPTER_ALPHA):
        super().__init__()
        self.up = nn.Linear(dim, rank)
        self.down = nn.Linear(rank, dim)
        self.alpha = mx.array(init_alpha, dtype=mx.float32)

    def __call__(self, x):
        return x + self.alpha * self.down(nn.gelu(self.up(x)))


class DesignHeadV7(nn.Module):
    """v6 trunk + Phase 6 (uncertainty) + Phase 7 (LoRA + features[18]) + Phase 8 (pref).

    Forward modes:
      visual_features = pre-pool (B, 7, 7, 320):
        runs MobileNet features[18] (trainable) → pool → 1280 → adapter → trunk → heads
      visual_features = pooled (B, 1280):
        legacy v6-style path; backbone stays frozen since features[18]
        wasn't applied at training time.  Use at inference when the caller
        only has pooled features.
    """

    def __init__(self, dropout: float = 0.5,
                 critique_dim: int = CRITIQUE_DIM,
                 adapter_rank: int = DEFAULT_ADAPTER_RANK,
                 adapter_alpha: float = DEFAULT_ADAPTER_ALPHA,
                 enable_adapter: bool = True,
                 enable_backbone: bool = True):
        super().__init__()

        self.enable_adapter = enable_adapter
        self.enable_backbone = enable_backbone

        if enable_backbone:
            self.backbone = MobileNetHeadConv()

        if enable_adapter:
            self.adapter = FeatureAdapter(1280, adapter_rank, adapter_alpha)

        # ── v6 trunk (warm-startable) ──
        self.vis_proj = nn.Linear(1280, 384)
        self.vis_norm = nn.LayerNorm(384)
        self.code_proj = nn.Linear(64, 128)
        self.code_norm = nn.LayerNorm(128)

        self.fc1 = nn.Linear(384 + 128, 256)
        self.ln1 = nn.LayerNorm(256)
        self.drop1 = nn.Dropout(dropout)

        self.fc2 = nn.Linear(256, 128)
        self.ln2 = nn.LayerNorm(128)
        self.drop2 = nn.Dropout(dropout * 0.8)

        self.fc3 = nn.Linear(128, 64)
        self.ln3 = nn.LayerNorm(64)
        self.drop3 = nn.Dropout(dropout * 0.6)

        self.output = nn.Linear(64, OUTPUT_DIM)
        self.log_var = nn.Linear(64, OUTPUT_DIM)

        # Critique aux head (Phase 5, dormant unless data plumbed)
        self.aux_fc1 = nn.Linear(64, 256)
        self.aux_fc2 = nn.Linear(256, 512)
        self.aux_out = nn.Linear(512, critique_dim)

        # Preference head (Phase 8) — per-dim logits
        self.pref_head = nn.Linear(64, OUTPUT_DIM)

    def trunk(self, visual_features, code_features=None):
        """Run backbone (if 4D) + adapter + v6 trunk → 64-dim representation."""
        if visual_features.ndim == 4:
            if not self.enable_backbone:
                raise RuntimeError("Got pre-pool features but backbone is disabled")
            x = self.backbone(visual_features)  # (B, 1280)
        else:
            x = visual_features  # already pooled

        if self.enable_adapter and hasattr(self, "adapter"):
            x = self.adapter(x)

        v = self.drop1(nn.gelu(self.vis_norm(self.vis_proj(x))))

        if code_features is not None:
            c = nn.gelu(self.code_norm(self.code_proj(code_features)))
        else:
            c = mx.zeros((v.shape[0], 128))

        h = mx.concatenate([v, c], axis=-1)
        h = self.drop1(nn.gelu(self.ln1(self.fc1(h))))
        h = self.drop2(nn.gelu(self.ln2(self.fc2(h))))
        return self.drop3(nn.gelu(self.ln3(self.fc3(h))))

    def __call__(self, visual_features, code_features=None,
                 return_aux: bool = False, return_uncertainty: bool = False,
                 return_preference: bool = False):
        h64 = self.trunk(visual_features, code_features)
        scores = mx.sigmoid(self.output(h64))
        out = [scores]
        if return_uncertainty:
            out.append(self.log_var(h64))
        if return_aux:
            aux = nn.gelu(self.aux_fc1(h64))
            aux = nn.gelu(self.aux_fc2(aux))
            out.append(self.aux_out(aux))
        if return_preference:
            out.append(self.pref_head(h64))
        return out[0] if len(out) == 1 else tuple(out)

    def param_count(self):
        return sum(p.size for _, p in tree_flatten(self.parameters()))


def warm_start_from_v6(model: DesignHeadV7, v6_path: Path) -> bool:
    if not v6_path.exists():
        print(f"[v7] no v6 checkpoint at {v6_path} — trunk init random")
        return False
    try:
        model.load_weights(str(v6_path), strict=False)
        print(f"[v7] warm-started trunk + adapter from v6: {v6_path.name}")
        return True
    except Exception as e:
        print(f"[v7] WARNING: v6 warm-start failed ({e})")
        return False


