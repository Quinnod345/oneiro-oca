# ═══════════════════════════════════════════════════
# MOBILENET FEATURES[18] — TRAINABLE 1×1 CONV + BN + ReLU6
# ═══════════════════════════════════════════════════


class MobileNetHeadConv(nn.Module):
    """The MobileNet V2 final block: 1×1 conv (320→1280) + BN + ReLU6, with
    the BatchNorm folded into the conv weights at init.

    BN folding (a.k.a. fused-BN) bakes the affine BN transformation
    γ·(x − μ)/√(σ² + ε) + β into the preceding convolution.  After folding:

        fused_w[c, ...] = conv_w[c, ...] * γ[c] / √(σ²[c] + ε)
        fused_b[c]      = β[c] − μ[c] * γ[c] / √(σ²[c] + ε)

    The forward pass collapses to: clip(conv_with_bias(x), 0, 6) → pool.
    Training has only ONE parameter set (the fused conv), no BN state to
    corrupt under weight_decay.  This is the same trick production
    inference pipelines use.

    Forward expects NHWC: (B, 7, 7, 320) → (B, 7, 7, 1280) → pool → (B, 1280).
    """

    def __init__(self):
        super().__init__()
        # 1×1 conv with bias enabled (so the folded β can live there).
        self.conv = nn.Conv2d(in_channels=320, out_channels=1280,
                              kernel_size=1, bias=True)

    def load_imagenet_weights(self, mobilenet_path: Path):
        """Load MobileNet's features[18] and fold its BN into the conv."""
        if not mobilenet_path.exists():
            raise FileNotFoundError(f"missing {mobilenet_path}")
        w = mx.load(str(mobilenet_path))

        conv_w = w["features.18.0.weight"]            # (1280, 1, 1, 320)
        bn_g = w["features.18.1.weight"]              # γ — BN scale
        bn_b = w["features.18.1.bias"]                # β — BN shift
        bn_m = w["features.18.1.running_mean"]        # μ
        bn_v = w["features.18.1.running_var"]         # σ²
        eps = 1e-5

        scale = bn_g / mx.sqrt(bn_v + eps)            # (1280,)
        # Broadcast scale into the (1280, 1, 1, 320) weight: same scale per
        # output channel, applied to all spatial+input dims.
        fused_w = conv_w * scale.reshape(1280, 1, 1, 1)
        fused_b = bn_b - bn_m * scale                 # (1280,)

        self.conv.weight = fused_w
        self.conv.bias = fused_b

    def __call__(self, x):
        # x: (B, 7, 7, 320)
        x = self.conv(x)                       # (B, 7, 7, 1280)
        x = mx.clip(x, 0.0, 6.0)               # ReLU6
        x = mx.mean(x, axis=(1, 2))            # AdaptiveAvgPool2d((1,1))
        return x


