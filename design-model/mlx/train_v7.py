# TRAINING
# ═══════════════════════════════════════════════════


def train(epochs=200, batch_size=16, learning_rate=1e-3,
          backbone_lr_ratio=DEFAULT_BACKBONE_LR_RATIO,
          weight_decay=0.05, warmup_steps=20, patience=30, dropout=0.5,
          aux_weight=DEFAULT_AUX_WEIGHT, pref_weight=DEFAULT_PREF_WEIGHT,
          nll_weight=DEFAULT_NLL_WEIGHT,
          adapter_rank=DEFAULT_ADAPTER_RANK,
          adapter_alpha=DEFAULT_ADAPTER_ALPHA,
          max_synth_pairs=DEFAULT_MAX_SYNTH_PAIRS,
          pair_overall_margin=DEFAULT_PAIR_MARGIN,
          pair_dim_margin=DEFAULT_PAIR_DIM_MARGIN,
          disable_aux=False, disable_adapter=False, disable_pref=False,
          disable_backbone=False, from_scratch=False):

    print("[v7] loading dataset...")
    dataset = FeatureDatasetV7(
        max_synth_pairs=max_synth_pairs,
        pair_overall_margin=pair_overall_margin,
        pair_dim_margin=pair_dim_margin,
    )
    print(f"[v7] {len(dataset)} samples (with pre-pool features)")
    print(f"[v7] critique embeddings matched: {dataset.n_matched}")

    train_idx, val_idx = dataset.split()
    print(f"[v7] split: {len(train_idx)} train, {len(val_idx)} val")
    print(f"[v7] pairs: {len(dataset.real_pairs)} real (flywheel) + "
          f"{len(dataset.synth_pairs)} synthetic (margin>{pair_overall_margin}) = "
          f"{len(dataset.all_pairs)} total")

    aux_enabled = (not disable_aux) and (dataset.n_matched >= MIN_AUX_SAMPLES)
    pref_enabled = (not disable_pref) and (len(dataset.all_pairs) >= 5)
    adapter_enabled = not disable_adapter
    backbone_enabled = not disable_backbone

    print(f"[v7] phases: "
          f"backbone={'on (trainable)' if backbone_enabled else 'off'} "
          f"adapter={'on' if adapter_enabled else 'off'} "
          f"uncertainty=on "
          f"pref={'on' if pref_enabled else 'off'} "
          f"aux={'on' if aux_enabled else 'off'}")

    model = DesignHeadV7(
        dropout=dropout,
        adapter_rank=adapter_rank,
        adapter_alpha=adapter_alpha,
        enable_adapter=adapter_enabled,
        enable_backbone=backbone_enabled,
    )
    if not from_scratch:
        warm_start_from_v6(model, V6_WEIGHTS_PATH)
    if backbone_enabled:
        model.backbone.load_imagenet_weights(MOBILENET_WEIGHTS_PATH)
        print(f"[v7] backbone features[18] loaded from {MOBILENET_WEIGHTS_PATH.name}")
    print(f"[v7] head: {model.param_count():,} params")

    # Per-parameter learning rate: backbone gets backbone_lr_ratio × head LR.
    # MLX optimizers don't natively support param groups, so we scale grads
    # of backbone params by the ratio inside the training loop.
    backbone_param_paths = (
        {f"backbone.{k}" for k, _ in tree_flatten(model.backbone.parameters())}
        if backbone_enabled else set()
    )

    optimizer = optim.AdamW(learning_rate=learning_rate, weight_decay=weight_decay)
    steps_per_epoch = max(1, len(train_idx) // batch_size)
    total_steps = epochs * steps_per_epoch

    def loss_fn(model, feats, targets, codes, crits, mask,
                feat_a, feat_b, code_a, code_b, winner, margin):
        scores, log_var, critique_preds, _pref = model(
            feats, codes,
            return_aux=True, return_uncertainty=True, return_preference=True,
        )
        nll = gaussian_nll_loss(scores, log_var, targets)
        total = nll_weight * nll

        if aux_enabled:
            aux = cosine_distance_masked(critique_preds, crits, mask)
            total = total + aux_weight * aux

        if pref_enabled and feat_a.shape[0] > 0:
            pref_a = model(feat_a, code_a, return_preference=True)[1]
            pref_b = model(feat_b, code_b, return_preference=True)[1]
            bt = bradley_terry_loss(pref_a, pref_b, winner, margin)
            total = total + pref_weight * bt

        return total

    loss_and_grad = nn.value_and_grad(model, loss_fn)

    best_val_loss = float("inf")
    patience_counter = 0
    global_step = 0
    best_per_dim = None
    best_uncertainty = None

    print(f"[v7] training: {epochs} epochs, batch {batch_size}, head_lr {learning_rate}, "
          f"backbone_lr {learning_rate * backbone_lr_ratio:.2e}")
    print(f"[v7] regularization: dropout={dropout}, weight_decay={weight_decay}")
    print()

    pref_rng = np.random.default_rng(0)

    for epoch in range(epochs):
        model.train()
        if backbone_enabled:
            model.backbone.eval()  # Keep BN in eval mode for the backbone

        t0 = time.time()
        rng = np.random.default_rng(epoch)
        shuffled = rng.permutation(train_idx).tolist()

        epoch_loss = 0.0
        epoch_steps = 0

        for start in range(0, len(shuffled), batch_size):
            batch_idx = shuffled[start:start + batch_size]
            feats, targets, codes, crits, mask = dataset.get_regression_batch(batch_idx)

            if pref_enabled and dataset.all_pairs:
                pref_batch_size = max(4, batch_size // 2)
                pref_idx = pref_rng.integers(
                    0, len(dataset.all_pairs),
                    size=min(pref_batch_size, len(dataset.all_pairs)),
                ).tolist()
            else:
                pref_idx = []
            feat_a, feat_b, code_a, code_b, winner, margin = \
                dataset.get_preference_batch(pref_idx)

            if global_step < warmup_steps:
                lr = learning_rate * global_step / max(warmup_steps, 1)
            else:
                progress = (global_step - warmup_steps) / max(total_steps - warmup_steps, 1)
                lr = 1e-6 + 0.5 * (learning_rate - 1e-6) * (1 + math.cos(math.pi * progress))
            optimizer.learning_rate = lr

            loss, grads = loss_and_grad(
                model, feats, targets, codes, crits, mask,
                feat_a, feat_b, code_a, code_b, winner, margin,
            )

            # Scale backbone gradients down so the conv adapts gently.
            if backbone_param_paths:
                grad_flat = tree_flatten(grads)
                scaled = []
                for path, g in grad_flat:
                    if path in backbone_param_paths:
                        scaled.append((path, g * backbone_lr_ratio))
                    else:
                        scaled.append((path, g))
                grads = tree_unflatten(scaled)

            grad_flat = tree_flatten(grads)
            grad_norm = mx.sqrt(sum(mx.sum(g * g) for _, g in grad_flat))
            if grad_norm > 1.0:
                scale = 1.0 / (grad_norm + 1e-8)
                grads = tree_map(lambda g: g * scale, grads)

            optimizer.update(model, grads)
            mx.eval(model.parameters(), optimizer.state, loss)

            epoch_loss += float(loss)
            epoch_steps += 1
            global_step += 1

        avg_train = epoch_loss / max(epoch_steps, 1)

        # Validation (on val split, regression only)
        model.eval()
        val_feats, val_targets, val_codes, _vc, _vm = dataset.get_regression_batch(val_idx)
        val_preds, val_log_var = model(val_feats, val_codes, return_uncertainty=True)
        val_loss = weighted_mse_loss(val_preds, val_targets)
        mx.eval(val_loss, val_preds, val_log_var)
        val_loss = float(val_loss)

        diff = mx.abs(val_preds - val_targets)
        mx.eval(diff)
        per_dim = [float(mx.mean(diff[:, i])) for i in range(OUTPUT_DIM)]

        std_per_dim = mx.sqrt(mx.exp(mx.clip(val_log_var, -7.0, 4.0)))
        mx.eval(std_per_dim)
        std_per_dim_list = [float(mx.mean(std_per_dim[:, i])) for i in range(OUTPUT_DIM)]

        elapsed = time.time() - t0

        if (epoch + 1) % 10 == 0 or val_loss < best_val_loss:
            print(f"  epoch {epoch + 1:4d}/{epochs} | "
                  f"train {avg_train:.4f} | val {val_loss:.4f} | "
                  f"lr {lr:.2e} | {elapsed:.2f}s")

        if val_loss < best_val_loss:
            best_val_loss = val_loss
            patience_counter = 0
            best_per_dim = per_dim
            best_uncertainty = std_per_dim_list

            WEIGHTS_DIR.mkdir(parents=True, exist_ok=True)
            model.save_weights(str(V7_WEIGHTS_PATH))

            dim_str = " | ".join(f"{SCORE_NAMES[i][:6]}={per_dim[i]:.3f}"
                                 for i in range(OUTPUT_DIM))
            print(f"  >>> best: {dim_str}")
        else:
            patience_counter += 1

        if patience_counter >= patience:
            print(f"\n[v7] early stopping at epoch {epoch + 1}")
            break

    print(f"\n[v7] training complete!")
    print(f"[v7] best val loss: {best_val_loss:.4f}")

    if best_per_dim:
        print(f"\n[v7] per-dim MAE | predicted std:")
        for i, name in enumerate(SCORE_NAMES):
            mae = best_per_dim[i]
            std = best_uncertainty[i] if best_uncertainty else 0.0
            bar = "█" * int(mae * 50)
            print(f"  {name:25s}: {mae:.4f}  σ={std:.3f}  {bar}")

    meta = {
        "best_val_loss": best_val_loss,
        "epochs": epoch + 1,
        "per_dim_mae": {n: best_per_dim[i] for i, n in enumerate(SCORE_NAMES)} if best_per_dim else {},
        "per_dim_predicted_std": {n: best_uncertainty[i] for i, n in enumerate(SCORE_NAMES)} if best_uncertainty else {},
        "param_count": model.param_count(),
        "backbone": "mobilenet_v2_imagenet (features[18] trainable)" if backbone_enabled else "frozen",
        "feature_dim": 1280,
        "phases": {
            "phase_5_aux": {
                "enabled": aux_enabled,
                "weight": aux_weight if aux_enabled else 0.0,
                "samples_matched": dataset.n_matched,
            },
            "phase_6_uncertainty": {
                "enabled": True,
                "loss": "gaussian_nll",
                "weight": nll_weight,
            },
            "phase_7_adapter": {
                "enabled": adapter_enabled,
                "rank": adapter_rank if adapter_enabled else None,
            },
            "phase_7_backbone": {
                "enabled": backbone_enabled,
                "trainable_block": "features[18] (1×1 320→1280 conv + BN + ReLU6)",
                "lr_ratio": backbone_lr_ratio if backbone_enabled else 0.0,
            },
            "phase_8_preference": {
                "enabled": pref_enabled,
                "weight": pref_weight if pref_enabled else 0.0,
                "real_pairs": len(dataset.real_pairs),
                "synth_pairs": len(dataset.synth_pairs),
                "synth_overall_margin": pair_overall_margin,
                "synth_dim_margin": pair_dim_margin,
                "max_synth_pairs": max_synth_pairs,
            },
        },
        "warm_start_from_v6": (not from_scratch) and V6_WEIGHTS_PATH.exists(),
    }
    with open(WEIGHTS_DIR / "train-v7-meta.json", "w") as f:
        json.dump(meta, f, indent=2)

    return meta


