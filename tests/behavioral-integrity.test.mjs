test('user completion requires an existing active intention and preserves its first completion receipt', async () => {
  const prospective = await import('../memory/prospective.js');
  await assert.rejects(prospective.complete(-1), /Valid intention/);
  await assert.rejects(prospective.complete(2147483647), /not found/);
  const pending = await prospective.intend('Isolated UI completion test', 'time', {at:'2099-01-01T00:00:00Z'});
  const first = await prospective.complete(pending.id);
  const again = await prospective.complete(pending.id);
  assert.equal(first.status, 'completed');
  assert.deepEqual(first.completed_at, again.completed_at);
  const cancelled = await prospective.intend('Isolated cancelled test', 'time', {at:'2099-01-01T00:00:00Z'});
  await prospective.cancel(cancelled.id);
  await assert.rejects(prospective.complete(cancelled.id), /no longer active/);
});

test('user experiment tools record a real lifecycle and attributed evidence, never an unstarted success', async () => {
  const { createUserOperations } = await import('../user-operations.js');
  const causal = await import('../causal/engine.js');
  const operations = createUserOperations({layers:{causal}}, {});
  const designed = await operations.experiment({causeDescription:'Isolated test: would a warmer cache reduce latency?', intervention:'Perform the cache run in a private fixture', expectedEffect:'Measured latency is lower'});
  const input = {experimentId:designed.id, actualOutcome:'Fixture measured 12ms', source:'Isolated fixture test', observation:'The local controlled fixture recorded 12ms'};
  await assert.rejects(operations.experimentOutcome(input), /began this experiment/);
  const started = await operations.experimentStarted({experimentId:designed.id});
  assert.equal(started.status, 'running');
  const complete = await operations.experimentOutcome(input);
  assert.equal(complete.status, 'completed');
  assert.equal(complete.causal_support, null, 'no numeric causal credit from a reported outcome');
  assert.equal(complete.metadata.outcomeEvidence[0].source, input.source);
  await assert.rejects(operations.experimentOutcome(input), /cannot accept results/);
});
