function reset(now) { emotion.restoreState({...structuredClone(baseline),savedAt:now}); }
test('ten minutes of idle is cadence-invariant and cannot manufacture satisfaction', t => {
  let now = 0; t.mock.method(Date,'now',()=>now);
  function run(step) {
    now=0; reset(now);
    for (let sec=0;sec<=600;sec+=step) { now=sec*1000; emotion.processIdle(sec/60); emotion.processInteroception(1,.2,.1,0); }
    return emotion.default.getState();
  }
  const fast=run(5),slow=run(60);
  for (const k of ['P','A','D','C','N']) assert.ok(Math.abs(fast._padcn[k]-slow._padcn[k])<1e-10,k);
  for (const k of ['novelty_seek','social_bond','competence','curiosity']) assert.ok(Math.abs(fast._drives[k].level-slow._drives[k].level)<1e-10,k);
  assert.equal(fast.satisfaction,0); assert.equal(fast._self_model.self_efficacy,baseline.selfModel.self_efficacy);
  assert.equal(fast._drives.competence.level,baseline.drives.competence.level);
});
test('zero/invalid magnitude, unchanged readings and returned state cannot mutate competence', () => {
  reset(Date.now());
  emotion.processSuccess(0); emotion.processSuccess('creative'); emotion.processInformationGain(0);
  emotion.processInteroception({energy:.2});
  for(let i=0;i<200;i++) emotion.processInteroception(1,.2,.1,0);
  const s=emotion.default.getState(); s._drives.competence.level=0;
  assert.equal(emotion.default.getState()._drives.competence.level,baseline.drives.competence.level);
  assert.ok(Object.values(emotion.default.getState()._padcn).every(Number.isFinite));
});
test('success and failure change affect differently; novelty alone cannot satiate competence', () => {
  reset(Date.now()); emotion.processSurprise(.8,'test');
  assert.equal(emotion.default.getState()._drives.competence.level,baseline.drives.competence.level);
  emotion.processInteraction(.8);
  assert.equal(emotion.default.getState()._self_model.self_efficacy,baseline.selfModel.self_efficacy,'positive social input is not measured competence');
  reset(Date.now()); emotion.processSuccess(.8); const success=emotion.default.getState();
  reset(Date.now()); emotion.processFailure(10,.8); const failure=emotion.default.getState();
  assert.ok(success.valence>failure.valence); assert.ok(failure.frustration>success.frustration);
  assert.ok(success._self_model.self_efficacy>failure._self_model.self_efficacy);
});
test('the complete affect state is durably restored without replay or satisfaction drift', async t => {
  let now=10000; t.mock.method(Date,'now',()=>now); reset(now);
  emotion.processFailure(10,.8); emotion.processIdle(7); await emotion.update();
  const before=emotion.snapshotState();
  reset(now); await emotion.restore(); const after=emotion.snapshotState();
  for(const k of ['padcn','channels','drives','selfModel','personality','failureStreak','lastIdleMinutes']) assert.deepEqual(after[k],before[k],k);
  now+=3600000; await emotion.restore();
  const cooled=emotion.snapshotState();
  assert.ok(Math.abs(cooled.padcn.P-cooled.personality.baseline_positive_affect)<Math.abs(before.padcn.P-before.personality.baseline_positive_affect));
  assert.deepEqual(cooled.drives,before.drives,'offline time does not satisfy wants');
});

async function prediction(expected=expectation) {
  return (await pool.query(`INSERT INTO hypotheses (domain,claim,prediction,confidence,status,source_data,created_at)
    VALUES ('fixture','Battery will be above threshold','battery >= 50',.7,'pending',$1,NOW()-INTERVAL '1 minute') RETURNING id`,
    [JSON.stringify({evaluation:expected})])).rows[0].id;
}
test('unobserved hypothesis is terminal unknown with no calibration or invented surprise', async () => {
  const id=await prediction(); const r=await hypothesis.test(id,{description:'Definitely battery >= 50',observed:{battery_pct:'unknown'}});
  assert.equal(r.status,'expired'); assert.equal(r.confirmed,null); assert.equal(r.surprise,null);
  const row=(await pool.query('SELECT * FROM hypotheses WHERE id=$1',[id])).rows[0];
  assert.equal(row.confidence_delta,0);
  assert.equal((await pool.query('SELECT COUNT(*)::int AS n FROM calibration_log')).rows[0].n,0);
  const ledger=(await pool.query('SELECT * FROM prediction_ledger WHERE hypothesis_id=$1',[id])).rows[0];
  assert.equal(ledger.prediction_error,null); assert.equal(ledger.status,'unverifiable');
});
test('concurrent observations calibrate once and conflicting replay cannot revise the outcome', async () => {
  const id=await prediction();
  const runs=await Promise.all([hypothesis.test(id,{observed:{battery_pct:90}}),hypothesis.test(id,{observed:{battery_pct:90}})]);
  assert.equal(runs.filter(r=>r.duplicate).length,1);
  assert.equal((await pool.query('SELECT COUNT(*)::int AS n FROM calibration_log')).rows[0].n,1);
  assert.equal((await pool.query('SELECT COUNT(*)::int AS n FROM prediction_ledger WHERE hypothesis_id=$1',[id])).rows[0].n,1);
  const replay=await hypothesis.test(id,{observed:{battery_pct:10}}); assert.equal(replay.duplicate,true);
  assert.equal((await pool.query('SELECT status FROM hypotheses WHERE id=$1',[id])).rows[0].status,'confirmed');
});
test('a falsified prediction is archived without rewording itself into another attempt', async () => {
  const id=await prediction(); const r=await hypothesis.test(id,{observed:{battery_pct:10}});
  assert.equal(r.status,'refuted'); assert.equal(r.revision.replacementHypothesisId,null); assert.equal(r.revision.error,undefined);
});
