test('causal completion needs actual execution plus supplied observation evidence, never an invented score', async () => {
  const c = await import('../causal/engine.js');
  const e = await c.designExperiment({causeDescription:'fixture',intervention:'measure fixture'});
  await assert.rejects(c.completeExperiment(e.id,{actualOutcome:'seems done'}),/outcomeEvidence/);
  const evidence={outcomeEvidence:[{id:'measurement',source:'fixture probe',observation:'result is 2'}]};
  assert.equal(await c.completeExperiment(e.id,{actualOutcome:'result is 2',metadata:evidence}),null,'unstarted experiment cannot complete');
  await c.startExperiment(e.id);
  await assert.rejects(c.completeExperiment(e.id,{actualOutcome:'result is 2',causalSupport:.8,metadata:evidence}),/verified comparison/);
  const done=await c.completeExperiment(e.id,{actualOutcome:'result is 2',metadata:evidence});
  assert.equal(done.status,'completed'); assert.equal(done.causal_support,null);
  assert.equal(await c.startExperiment(e.id),null,'closed experiment cannot resurrect');
  const abandoned=await c.designExperiment({causeDescription:'fixture',intervention:'never executed'});
  const expired=await c.completeExperiment(abandoned.id,{status:'abandoned',actualOutcome:'timed out'});
  assert.equal(expired.causal_support,null); assert.equal(expired.outcome_valence,null);
});
