import test from 'node:test';
import assert from 'node:assert/strict';
import pg from 'pg';
import express from 'express';
import { randomBytes } from 'node:crypto';
import { readFile } from 'node:fs/promises';

// Forgetting from the Memory page, end to end against the real modules: the workspace routes set and clear
// forgotten_at, and every recall path (episodic recall and recent, semantic query and category, graph passage
// ranking, the workspace browse/search/inspect routes) leaves a forgotten record out until it is restored.
// A private schema keeps the real database untouched; hash embeddings keep it offline and deterministic.
const dsn = process.env.OCA_TEST_DATABASE_URL || 'postgres://localhost/oneiro';
const schema = 'forget_test_' + randomBytes(6).toString('hex');
const admin = new pg.Pool({ connectionString: dsn });
await admin.query('CREATE SCHEMA ' + schema);
const isolated = new URL(dsn); isolated.searchParams.set('options', '-c search_path=' + schema + ',public');
process.env.DATABASE_URL = isolated.toString();
process.env.ONEIRO_EMBED_BACKEND = 'hash';
const { pool } = await import('../event-bus.js');
for (const table of ['episodic_memory', 'semantic_memory', 'semantic_evidence', 'cognitive_events', 'entity_mentions']) {
  await pool.query(`CREATE TABLE ${table} (LIKE public.${table} INCLUDING DEFAULTS INCLUDING CONSTRAINTS)`);
  await pool.query(`ALTER TABLE ${table} ALTER COLUMN id DROP DEFAULT`);
  await pool.query(`ALTER TABLE ${table} ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`);
}
await pool.query(await readFile(new URL('../migrations/070_memory_forget.sql', import.meta.url), 'utf8'));
const episodic = (await import('../memory/episodic.js')).default;
const semantic = (await import('../memory/semantic.js')).default;
const entityGraph = (await import('../memory/entity-graph.js')).default;
const { createUserWorkspace } = await import('../user-workspace.js');

const app = express(); app.use(express.json());
app.use(createUserWorkspace({ pool, queue: {}, operations: {}, runPending: async () => {}, llmStatus: () => ({}) }).router);
const server = app.listen(0, '127.0.0.1'); await new Promise(r => server.once('listening', r));
const call = async (path, method = 'GET', body) => {
  const r = await fetch(`http://127.0.0.1:${server.address().port}${path}`, { method,
    headers: body ? { 'content-type': 'application/json' } : {}, body: body ? JSON.stringify(body) : undefined });
  return { status: r.status, body: await r.json() };
};
test.after(async () => {
  await new Promise(r => server.close(r));
  await pool.end(); await admin.query('DROP SCHEMA ' + schema + ' CASCADE'); await admin.end();
});

const oat = await episodic.store({ eventType: 'user_report', content: 'Quinn takes oat milk in his coffee every morning' });
const boston = await episodic.store({ eventType: 'user_report', content: 'Quinn visited his sister in Boston last spring' });
const claim = await semantic.learn('Quinn prefers oat milk over dairy', { category: 'preference', sourceType: 'user_report', confidence: 0.8 });
const other = await semantic.learn('Quinn works on Oneiro late at night', { category: 'preference', sourceType: 'user_report', confidence: 0.8 });
const ids = rows => rows.map(r => r.id);

test('forgetting an experience hides it from every recall path, and restoring brings it back unchanged', async () => {
  const before = (await pool.query('SELECT * FROM episodic_memory WHERE id=$1', [oat.id])).rows[0];
  assert.ok(ids(await episodic.recall('oat milk coffee', { limit: 5 })).includes(oat.id));

  const forgot = await call(`/oca/ui/memory/experience/${oat.id}/forget`, 'POST', { reason: 'Not true any more' });
  assert.equal(forgot.status, 200);
  assert.equal(forgot.body.forgotten, true); assert.equal(forgot.body.changed, true);
  assert.match(forgot.body.message, /Undo/);

  assert.ok(!ids(await episodic.recall('oat milk coffee', { limit: 5 })).includes(oat.id), 'vector recall (/oca/remember) skips it');
  assert.ok(ids(await episodic.recall('oat milk coffee', { limit: 5 })).includes(boston.id), 'other memories still recall');
  assert.ok(!ids(await episodic.recent(10)).includes(oat.id), 'chronological recall skips it');
  await pool.query("INSERT INTO entity_mentions(entity_id, source_type, source_id) VALUES (7,'episode',$1),(7,'episode',$2)", [oat.id, boston.id]);
  assert.deepEqual(ids(await entityGraph.rankPassagesByPPR(new Map([[7, 0.5]]), { limit: 5 })), [boston.id], 'graph recall (/oca/hippo-recall) skips it');
  assert.ok(!ids((await call('/oca/ui/memory-recent?kind=experience')).body.results).includes(oat.id), 'browse skips it');
  assert.equal((await call('/oca/ui/memory-search?kind=experience&q=oat')).body.results.length, 0, 'word search skips it');
  const inspect = await call(`/oca/ui/memory/experience/${oat.id}`);
  assert.equal(inspect.status, 410); assert.equal(inspect.body.forgotten, true);
  const listed = (await call('/oca/ui/memory-forgotten')).body.results;
  assert.deepEqual(listed.map(r => [r.kind, r.id]), [['experience', oat.id]]);

  const again = await call(`/oca/ui/memory/experience/${oat.id}/forget`, 'POST', {});
  assert.equal(again.status, 200); assert.equal(again.body.changed, false, 'a repeated tap changes nothing');

  const restored = await call(`/oca/ui/memory/experience/${oat.id}/restore`, 'POST', {});
  assert.equal(restored.status, 200); assert.equal(restored.body.forgotten, false); assert.equal(restored.body.changed, true);
  assert.ok(ids(await episodic.recall('oat milk coffee', { limit: 5 })).includes(oat.id));
  assert.equal((await call('/oca/ui/memory-search?kind=experience&q=oat')).body.results[0].id, oat.id);
  assert.equal((await call(`/oca/ui/memory/experience/${oat.id}`)).status, 200);
  const after = (await pool.query('SELECT * FROM episodic_memory WHERE id=$1', [oat.id])).rows[0];
  for (const column of ['content', 'event_type', 'timestamp', 'importance_score']) assert.deepEqual(after[column], before[column], column);
  assert.equal(after.forgotten_at, null);

  const log = (await pool.query("SELECT kind, record_id, action, reason FROM memory_forget_log WHERE kind='experience' ORDER BY id")).rows;
  assert.deepEqual(log, [
    { kind: 'experience', record_id: oat.id, action: 'forget', reason: 'Not true any more' },
    { kind: 'experience', record_id: oat.id, action: 'restore', reason: null }]);
  const logColumns = (await pool.query("SELECT column_name FROM information_schema.columns WHERE table_schema=$1 AND table_name='memory_forget_log'", [schema])).rows.map(r => r.column_name);
  assert.ok(!logColumns.some(c => /content|concept|text|excerpt/.test(c)), 'the audit trail keeps no copy of the memory');
});

test('forgetting a claim hides it from semantic recall, and re-learning the same words starts a fresh claim', async () => {
  assert.ok(ids(await semantic.query('oat milk dairy', { limit: 5 })).includes(claim.id));
  assert.equal((await call(`/oca/ui/memory/knowledge/${claim.id}/forget`, 'POST', {})).status, 200);
  assert.ok(!ids(await semantic.query('oat milk dairy', { limit: 5 })).includes(claim.id), 'semantic recall (/oca/know) skips it');
  assert.deepEqual(ids(await semantic.getCategory('preference')), [other.id]);
  assert.ok(!ids((await call('/oca/ui/memory-recent?kind=knowledge')).body.results).includes(claim.id));
  assert.equal((await call('/oca/ui/memory-search?kind=all&q=oat')).body.results.every(r => !(r.kind === 'knowledge' && r.id === claim.id)), true);
  assert.equal((await call(`/oca/ui/memory/knowledge/${claim.id}`)).status, 410);
  const relearned = await semantic.learn('Quinn prefers oat milk over dairy', { category: 'preference', sourceType: 'user_report', confidence: 0.8 });
  assert.notEqual(relearned.id, claim.id, 'new evidence never quietly reinforces a forgotten claim');
  await pool.query('DELETE FROM semantic_memory WHERE id=$1', [relearned.id]);
  assert.equal((await call(`/oca/ui/memory/knowledge/${claim.id}/restore`, 'POST', {})).body.forgotten, false);
  assert.ok(ids(await semantic.query('oat milk dairy', { limit: 5 })).includes(claim.id));
});

test('the Memory page can browse without a query: newest first, both kinds share a mixed page, one kind pages back', async () => {
  const all = await call('/oca/ui/memory-recent');
  assert.equal(all.status, 200); assert.equal(all.body.kind, 'all'); assert.equal(all.body.next, null);
  assert.deepEqual(new Set(all.body.results.map(r => r.kind)), new Set(['experience', 'knowledge']));
  for (const r of all.body.results) { assert.ok(r.recorded_at); assert.ok(r.origin); assert.equal(r.embedding, undefined); }
  const times = all.body.results.map(r => new Date(r.recorded_at).getTime());
  assert.deepEqual(times, [...times].sort((a, b) => b - a));
  const page = await call('/oca/ui/memory-recent?kind=experience&limit=1');
  assert.equal(page.body.results.length, 1); assert.equal(page.body.results[0].id, boston.id); assert.ok(page.body.next);
  const older = await call('/oca/ui/memory-recent?kind=experience&limit=1&before=' + encodeURIComponent(page.body.next));
  assert.deepEqual(ids(older.body.results), [oat.id]);
  assert.equal((await call('/oca/ui/memory-recent?kind=other')).status, 400);
  assert.equal((await call('/oca/ui/memory-recent?kind=all&before=yesterday-ish')).status, 400);
});

test('forget and restore refuse unknown collections, malformed ids and records that do not exist', async () => {
  assert.equal((await call('/oca/ui/memory/other/1/forget', 'POST', {})).status, 404);
  assert.equal((await call('/oca/ui/memory/experience/1.5/forget', 'POST', {})).status, 400);
  assert.equal((await call('/oca/ui/memory/experience/99999999999/forget', 'POST', {})).status, 400);
  const missing = await call('/oca/ui/memory/knowledge/999999/restore', 'POST', {});
  assert.equal(missing.status, 404); assert.match(missing.body.error, /refresh/);
});

