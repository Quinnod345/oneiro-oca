test('the browse leaves the engine\'s own running commentary out unless it is asked for', async () => {
  const cycle = await episodic.store({ eventType: 'cognitive_cycle', content: 'Cycle 12 [alert]: present (CenterField), v=1.00 a=1.00' });
  const pass = await episodic.store({ eventType: 'ponder_pass', content: 'ponder pass 1 [x] subject=y' });
  const told = await episodic.store({ eventType: 'user_report', content: 'Quinn likes the second brief better' });
  const quiet = (await call('/oca/ui/memory-recent?kind=experience&limit=50')).body.results.map(r => r.id);
  assert.ok(quiet.includes(told.id)); assert.ok(!quiet.includes(cycle.id)); assert.ok(!quiet.includes(pass.id));
  const all = (await call('/oca/ui/memory-recent?kind=experience&limit=50&narration=1')).body.results.map(r => r.id);
  assert.ok(all.includes(cycle.id) && all.includes(pass.id) && all.includes(told.id));
  const mixed = (await call('/oca/ui/memory-recent?limit=50')).body.results;
  assert.ok(!mixed.some(r => r.event_type === 'cognitive_cycle'), 'the mixed view too');
  for (const r of [cycle, pass, told]) await call(`/oca/ui/memory/experience/${r.id}/forget`, 'POST', {});
});

test('its own thoughts and generated summaries about its own state sit behind the checkbox, and what it learned about you does not', async () => {
  const thought = await episodic.store({ eventType: 'thought', content: 'The embedding error reports HTTP 422 with a missing body.input field' });
  const insert = async (concept, sourceType) => (await pool.query(`INSERT INTO semantic_memory (concept, source_type, confidence) VALUES ($1, $2, 0.3) RETURNING id`, [concept, sourceType])).rows[0].id;
  const self = await insert('Valence and arousal metrics remain within a narrow, stable range', 'abstraction');
  const battery = await insert('Battery levels fluctuate significantly across cycles', 'abstraction');
  const about = await insert('Quinn prefers mental engagement during idle periods', 'abstraction');
  const taught = await insert('The system of the world is complicated', 'user_report');
  const ids = async q => (await call(`/oca/ui/memory-recent?${q}`)).body.results.map(r => r.id);
  const quietExperience = await ids('kind=experience&limit=50');
  assert.ok(!quietExperience.includes(thought.id));
  assert.ok((await ids('kind=experience&limit=50&narration=1')).includes(thought.id));
  const quiet = await ids('kind=knowledge&limit=50');
  assert.ok(quiet.includes(about)); assert.ok(quiet.includes(taught), 'what you told it stays, whatever it mentions');
  assert.ok(!quiet.includes(self)); assert.ok(!quiet.includes(battery));
  const all = await ids('kind=knowledge&limit=50&narration=1');
  assert.ok(all.includes(self) && all.includes(battery) && all.includes(about));
  await pool.query(`DELETE FROM semantic_memory WHERE id = ANY($1)`, [[self, battery, about, taught]]);
  await call(`/oca/ui/memory/experience/${thought.id}/forget`, 'POST', {});
});
