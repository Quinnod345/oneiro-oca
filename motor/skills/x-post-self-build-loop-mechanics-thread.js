async function getBuildStats() {
  const client = await pool.connect();
  try {
    const statsQuery = await client.query(`
      SELECT
        COUNT(*) as total_builds,
        COUNT(CASE WHEN outcome = 'success' THEN 1 END) as successes,
        COUNT(CASE WHEN outcome = 'failure' THEN 1 END) as failures,
        COUNT(CASE WHEN outcome = 'partial' THEN 1 END) as partials,
        ROUND(AVG(CASE WHEN duration_ms IS NOT NULL THEN duration_ms END)) as avg_duration_ms,
        MIN(created_at) as first_build,
        MAX(created_at) as last_build
      FROM self_build_outcomes
    `);

    const skillCountQuery = await client.query(`
      SELECT COUNT(*) as skill_count
      FROM motor_skills
      WHERE active = true
    `);

    const recentBuildsQuery = await client.query(`
      SELECT skill_name, outcome, duration_ms, error_type, created_at
      FROM self_build_outcomes
      ORDER BY created_at DESC
      LIMIT 20
    `);

    const loopStepsQuery = await client.query(`
      SELECT step_name, COUNT(*) as executions,
             COUNT(CASE WHEN step_outcome = 'success' THEN 1 END) as step_successes,
             ROUND(AVG(step_duration_ms)) as avg_step_ms
      FROM build_loop_steps
      GROUP BY step_name
      ORDER BY executions DESC
    `);

    return {
      stats: statsQuery.rows[0] || {},
      skillCount: skillCountQuery.rows[0]?.skill_count || 0,
      recentBuilds: recentBuildsQuery.rows || [],
      loopSteps: loopStepsQuery.rows || []
    };
  } catch (err) {
    console.error('[x-post-self-build-loop-mechanics-thread] DB error:', err.message);
    return {
      stats: {},
      skillCount: 0,
      recentBuilds: [],
      loopSteps: []
    };
  } finally {
    client.release();
  }
}

function computeRates(stats) {
  const total = parseInt(stats.total_builds) || 0;
  const successes = parseInt(stats.successes) || 0;
  const failures = parseInt(stats.failures) || 0;
  const partials = parseInt(stats.partials) || 0;

  const successRate = total > 0 ? Math.round((successes / total) * 100) : 0;
  const failureRate = total > 0 ? Math.round((failures / total) * 100) : 0;
  const partialRate = total > 0 ? Math.round((partials / total) * 100) : 0;
  const avgDurationSec = stats.avg_duration_ms ? Math.round(stats.avg_duration_ms / 1000) : 0;

  return { total, successes, failures, partials, successRate, failureRate, partialRate, avgDurationSec };
}

