async function postTweetViaPerekaboo(text) {
  try {
    const escaped = text.replace(/'/g, "'\\''");
    const result = await motor.runShellCommand(`peekaboo x post '${escaped}'`);
    return { success: true, result };
  } catch (err) {
    return { success: false, error: err.message };
  }
}

async function postTweetViaBrowser(text, isFirst = false) {
  try {
    if (isFirst) {
      await motor.openUrl('https://x.com/compose/tweet');
      await new Promise(r => setTimeout(r, 3000));
    }

    await motor.click({ x: 760, y: 400 });
    await new Promise(r => setTimeout(r, 500));
    await motor.type(text);
    await new Promise(r => setTimeout(r, 1000));

    // Cmd+Enter to post
    await motor.press('cmd+return');
    await new Promise(r => setTimeout(r, 2500));

    return { success: true };
  } catch (err) {
    return { success: false, error: err.message };
  }
}

